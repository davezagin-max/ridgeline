"""Builds the heightmap the web app ships with.

    uv run python -m terrain.build                # real data from AWS Terrain Tiles
    uv run python -m terrain.build --synthetic    # offline stand-in, labelled as such

Real mode downloads about 15 Terrarium PNG tiles (zoom 12, roughly 29 m per pixel
at this latitude) into `tools/.cache/`, stitches them, resamples to the app grid and
writes `public/data/wasatch.u16` plus `public/data/wasatch.json`.
"""

from __future__ import annotations

import argparse
from datetime import date
from pathlib import Path

from .fetch import build_mosaic
from .heightmap import resample, write_heightmap
from .synthetic import synthetic_terrain
from .tiles import Bounds, tile_range

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_OUT = ROOT.parent / "public" / "data"
DEFAULT_CACHE = ROOT / ".cache" / "terrarium"

# Cottonwood Canyons through Park City.
WASATCH = Bounds(west=-111.83, south=40.52, east=-111.45, north=40.70)
WIDTH = 1024
HEIGHT = 640
ZOOM = 12

SOURCE = {
    "name": "Terrain Tiles (Mapzen / Tilezen Joerd), Terrarium encoding",
    "url": "https://registry.opendata.aws/terrain-tiles/",
    "license": "https://github.com/tilezen/joerd/blob/master/docs/attribution.md",
    "attribution": (
        "Elevation: Terrain Tiles by Mapzen, hosted by AWS Open Data. "
        "United States 3DEP (formerly NED) terrain data courtesy of the U.S. Geological Survey."
    ),
    "processing": (
        "Zoom 12 tiles mosaicked, bilinearly resampled to a regular longitude/latitude "
        "grid, and stored as 16-bit integers in 0.1 m steps."
    ),
}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    parser.add_argument("--synthetic", action="store_true", help="write made-up terrain instead")
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    parser.add_argument("--cache", type=Path, default=DEFAULT_CACHE)
    parser.add_argument("--zoom", type=int, default=ZOOM)
    args = parser.parse_args()

    if args.synthetic:
        elevation = synthetic_terrain(WIDTH, HEIGHT)
        extra = {
            "synthetic": True,
            "source": {
                "name": "Synthetic terrain (seeded noise), not real elevation",
                "url": None,
                "license": None,
                "attribution": "Synthetic terrain generated by tools/terrain/synthetic.py.",
                "processing": "Generated, not measured.",
            },
            "accessed": date.today().isoformat(),
        }
    else:
        tiles = tile_range(WASATCH, args.zoom)
        print(f"Fetching {len(tiles.tiles())} tiles at zoom {args.zoom} (cached in {args.cache})")
        mosaic = build_mosaic(tiles, args.cache)
        elevation = resample(mosaic, WASATCH, WIDTH, HEIGHT)
        extra = {
            "synthetic": False,
            "source": {**SOURCE, "zoom": args.zoom, "tiles": len(tiles.tiles())},
            "accessed": date.today().isoformat(),
        }

    meta = write_heightmap(args.out, "wasatch", elevation, WASATCH, extra)
    size_kb = (args.out / "wasatch.u16").stat().st_size / 1024
    print(
        f"Wrote {meta['width']} x {meta['height']} samples, "
        f"{meta['cellX']} x {meta['cellY']} m cells, "
        f"{meta['minElevation']} to {meta['maxElevation']} m, {size_kb:.0f} KB"
    )


if __name__ == "__main__":
    main()
